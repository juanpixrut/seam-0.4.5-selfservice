// This block guards two real, separate vulnerabilities found 2026-08-04
// via adversarial testing, both on the same page, both via the same
// root cause: asset name/status/type are genuinely user-editable, and
// every asset on the map renders one.
//
//  1. markersJSON used to be hand-assembled via raw fmt.Sprintf, no
//     escaping at all -- a "</script>" sequence in an asset's name
//     broke out of the <script> tag it was embedded in. Fixed by
//     marshaling via encoding/json, which HTML-escapes </>/& by
//     default specifically for safe script-tag embedding.
//  2. Even with (1) fixed, the client-side JS built each popup via raw
//     string concatenation into bindPopup() (which renders its string
//     argument as HTML) -- JSON.parse reverses (1)'s escaping
//     client-side, so a malicious asset name would still execute as
//     live HTML in the popup. Fixed by building the popup via DOM APIs
//     (createElement/textContent) instead of an HTML string at all.
//
// Neither test can execute a real browser to prove the exploit no
// longer fires (that needs an actual JS engine, out of scope for this
// Go test suite) -- what they can and do confirm: (1) the rendered
// output correctly escapes a script-tag-breakout payload at the JSON
// layer, and (2) the vulnerable bindPopup(string) call pattern is
// genuinely gone from the rendered JS source, replaced by the safe
// DOM-construction pattern.
func TestMapViewPage_MarkerNameWithScriptTagIsEscapedInJSON(t *testing.T) {
	data := MapViewData{
		Markers: []MapMarker{
			{ID: 1, Name: `</script><script>alert(document.cookie)</script>`, Status: "active", TypeName: "Excavator", Lat: 1.0, Lng: 2.0},
		},
	}
	html := mi.RenderToString(MapViewPage(data, nil))

	if strings.Contains(html, "</script><script>alert") {
		t.Fatalf("the malicious asset name's literal \"</script><script>\" sequence appears unescaped in the rendered page -- this would break out of the <script> tag:\n%s", html)
	}
	// encoding/json's default HTML-escaping produces \u003c/\u003e for
	// < and >, not literal characters -- confirming the escaped form is
	// present (not just the absence of the raw form) proves real
	// escaping happened, not e.g. the marker being silently dropped.
	if !strings.Contains(html, `\u003c/script\u003e`) {
		t.Errorf("expected the JSON-escaped form (\\u003c/script\\u003e) of the malicious name in the output -- got neither the raw nor escaped form, suggesting the marker itself went missing:\n%s", html)
	}
}

func TestMapViewPage_PopupBuiltViaDOMNotHTMLStringConcatenation(t *testing.T) {
	data := MapViewData{Markers: []MapMarker{{ID: 1, Name: "Test Asset", Status: "active", TypeName: "Excavator", Lat: 1.0, Lng: 2.0}}}
	html := mi.RenderToString(MapViewPage(data, nil))

	if strings.Contains(html, "bindPopup('<strong>'") || strings.Contains(html, `'<strong>' + m.name`) {
		t.Error("rendered JS still contains the vulnerable raw-HTML-string bindPopup call -- the DOM-construction fix may have regressed")
	}
	for _, want := range []string{"createElement('strong')", "textContent = m.name", "createTextNode(m.type)", "marker.bindPopup(popup)"} {
		if !strings.Contains(html, want) {
			t.Errorf("rendered JS missing expected safe DOM-construction pattern %q", want)
		}
	}
}

func TestMapViewPage_NoMarkers_RendersEmptyArrayNotBrokenJS(t *testing.T) {
	// The zero-marker case: json.Marshal(nil slice) produces "null", not
	// "[]" -- markers.forEach would throw a TypeError client-side on a
	// null value. Confirms the explicit markersJSON = "[]" fallback
	// actually takes effect for a genuinely empty/nil Markers slice.
	html := mi.RenderToString(MapViewPage(MapViewData{}, nil))
	if !strings.Contains(html, "var markers = [];") {
		t.Error("expected \"var markers = [];\" for an empty marker set -- got something else, possibly \"null\" from json.Marshal(nil)")
	}
}

// TestFSMEditorPage_FSMNameWithQuoteCannotBreakOutOfAttribute guards a
// third, independently-found instance of the same vulnerability class
// as T-63's Map-page XSS: mi.Raw(fmt.Sprintf(...)) interpolated
// data.FSMName -- a real FSM's name, genuinely user-editable --
// directly into an HTML attribute (fsm-name="%s") with no escaping at
// all. mi.Raw bypasses minty's own automatic per-attribute escaping
// entirely (confirmed directly from minty's source), so this needed
// its own explicit html.EscapeString, matching what Element.Render
// does for every other attribute in the app. Found by checking every
// other mi.Raw(fmt.Sprintf(...)) call site after T-63, not by luck --
// there were three in the whole codebase; this was the one T-63's own
// investigation hadn't reached yet.
func TestFSMEditorPage_FSMNameWithQuoteCannotBreakOutOfAttribute(t *testing.T) {
	data := FSMEditorData{
		FSMID:     "42",
		FSMName:   `Evil" onmouseover="alert(document.cookie)" x="`,
		CSRFToken: "tok",
	}
	out := mi.RenderToString(FSMEditorPage(data, nil))

	if strings.Contains(out, `onmouseover="alert`) {
		t.Fatalf("the malicious FSM name's onmouseover attribute appears live in the rendered HTML -- the quote broke out of fsm-name=\"...\":\n%s", out)
	}
	if !strings.Contains(out, "&#34;") && !strings.Contains(out, "&quot;") {
		t.Errorf("expected the FSM name's quote character to appear HTML-escaped (&#34; or &quot;) -- got neither, suggesting the name was dropped rather than escaped:\n%s", out)
	}
}

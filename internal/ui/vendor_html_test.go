// TestMapViewRedirectsWhenDisabled verifies GET /map redirects to /assets when
// EnableMap is false in the config.
func TestMapViewRedirectsWhenDisabled(t *testing.T) {
	srv := mockOLU(t, nil)
	defer srv.Close()
	h := newHandler(t, srv)
	h.config.EnableMap = false

	req := httptest.NewRequest("GET", "/map", nil)
	rec := httptest.NewRecorder()
	h.MapView(rec, req)

	if rec.Code != http.StatusSeeOther {
		t.Errorf("expected 303 SeeOther when map disabled, got %d", rec.Code)
	}
	if loc := rec.Header().Get("Location"); loc != "/assets" {
		t.Errorf("expected redirect to /assets, got %q", loc)
	}
}


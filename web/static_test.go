// TestVendorFilesPresent verifies every expected asset is in the embedded FS.
func TestVendorFilesPresent(t *testing.T) {
	for _, f := range expectedVendorFiles {
		f := f
		t.Run(f.path, func(t *testing.T) {
			data, err := fs.ReadFile(web.Static, f.path)
			if err != nil {
				t.Fatalf("vendor file missing from embedded FS: %s\n"+
					"  Run: make build   (or check release.sh Tailwind step ran)\n"+
					"  Error: %v", f.path, err)
			}
			if len(data) < f.minBytes {
				t.Errorf("%s: too small — got %d bytes, want at least %d\n"+
					"  File may be empty or a stub placeholder.", f.path, len(data), f.minBytes)
			}
			if f.mustContain != "" && !strings.Contains(string(data), f.mustContain) {
				t.Errorf("%s: must contain %q but doesn't\n"+
					"  File may be corrupt or replaced with wrong content.", f.path, f.mustContain)
			}
			if f.mustNotContain != "" && strings.Contains(string(data), f.mustNotContain) {
				t.Errorf("%s: must NOT contain %q but does\n"+
					"  File may be a CDN stub instead of the real vendored asset.", f.path, f.mustNotContain)
			}
		})
	}
}

// TestMaterialIconsFontPath verifies the CSS @font-face points to the local
// WOFF2 path, not to fonts.gstatic.com. If this fails the font loads from an
// external CDN instead of the vendored file.
func TestMaterialIconsFontPath(t *testing.T) {
	data, err := fs.ReadFile(web.Static, "static/vendor/material-icons.css")
	if err != nil {
		t.Fatalf("material-icons.css missing: %v", err)
	}
	css := string(data)

	badSources := []string{
		"fonts.gstatic.com",
		"fonts.googleapis.com",
		"unpkg.com",
	}
	for _, bad := range badSources {
		if strings.Contains(css, bad) {
			t.Errorf("material-icons.css references external origin %q — "+
				"must use a local /static/vendor/ path only", bad)
		}
	}
	if !strings.Contains(css, "/static/vendor/fonts/") {
		t.Errorf("material-icons.css @font-face does not reference /static/vendor/fonts/ — " +
			"font will not load from the vendored WOFF2")
	}
}

// TestLeafletCSSImagePaths verifies the Leaflet CSS uses relative image paths
// that resolve correctly from the vendor/ directory. The images/ subdirectory
// exists at the same level as leaflet@1.9.4.css specifically for this.
func TestLeafletCSSImagePaths(t *testing.T) {
	data, err := fs.ReadFile(web.Static, "static/vendor/leaflet@1.9.4.css")
	if err != nil {
		t.Fatalf("leaflet CSS missing: %v", err)
	}
	css := string(data)

	// Leaflet's CSS references marker images like url(images/marker-icon.png).
	// We need the relative path to work — absolute or CDN paths would break.
	if !strings.Contains(css, "images/marker-icon.png") {
		t.Error("leaflet CSS does not contain expected relative image reference 'images/marker-icon.png'")
	}

	// Must NOT contain external URLs inside url() resource declarations.
	// Note: comment-only references (e.g. bug tracker links) are acceptable.
	for _, bad := range []string{"url(http://", "url(https://"} {
		if strings.Contains(css, bad) {
			t.Errorf("leaflet CSS has external url() reference %q — "+
				"images will not load in an air-gapped deployment", bad)
		}
	}
}

// TestTailwindCSSNotScript verifies the committed tailwind.css is a real
// generated CSS file, not the CDN play script (which is JavaScript).
func TestTailwindCSSNotScript(t *testing.T) {
	data, err := fs.ReadFile(web.Static, "static/css/tailwind.css")
	if err != nil {
		t.Fatalf("tailwind.css missing: %v", err)
	}
	css := string(data)

	if strings.Contains(css, "function ") || strings.Contains(css, "var ") {
		t.Error("tailwind.css appears to contain JavaScript — " +
			"it may be the CDN play script rather than a generated CSS file. " +
			"Run: npx tailwindcss -c tailwind.config.js -i scripts/tailwind.input.css -o web/static/css/tailwind.css --minify")
	}
}


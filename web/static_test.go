// TestIconNamesInFont verifies that every Material Icon name referenced in the
// Go source is present as a ligature in the vendored WOFF2 font.
//
// This test uses the pre-generated ligature list committed at
// web/static/vendor/material-icons-ligatures.txt (regenerated by make check-icons).
// It does not require Python or fonttools to run — Go test time is self-contained.
//
// What it catches: using an icon name (e.g. "new_icon") that does not exist in
// the font version we have vendored. The icon would silently render as nothing.
//
// To add a new icon: use it in source, then run `make check-icons` to verify it
// is in the font and to regenerate the ligature list. Then commit both together.
func TestIconNamesInFont(t *testing.T) {
	// Load the committed ligature list from the embedded FS
	data, err := fs.ReadFile(web.Static, "static/vendor/material-icons-ligatures.txt")
	if err != nil {
		t.Fatalf("material-icons-ligatures.txt missing — run: make check-icons\n%v", err)
	}

	ligatures := make(map[string]bool)
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		ligatures[line] = true
	}
	if len(ligatures) < 2000 {
		t.Fatalf("ligature list suspiciously small (%d entries) — regenerate with: make check-icons",
			len(ligatures))
	}

	// Scan Go source files for icon-name candidates.
	// Strategy: any double-quoted string matching [a-z][a-z_0-9]{2,39} that is
	// also present in the ligature table is considered a referenced icon.
	// This matches the Python script's approach exactly.
	iconRe := regexp.MustCompile(`"([a-z][a-z_0-9]{2,39})"`)

	var goFiles []string
	err = filepath.WalkDir("../internal/ui", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(p, ".go") && !strings.HasSuffix(p, "_test.go") {
			goFiles = append(goFiles, p)
		}
		return nil
	})
	if err != nil {
		t.Skipf("cannot walk source tree (non-source environment?): %v", err)
		return
	}

	// dashboardengine's JSON schemas (assets-dashboard.json etc.) declare
	// icons as plain "icon": "name" JSON values, not Go string literals --
	// MOD-2 moved dashboard.go's hardcoded dashStatCard(..., "crisis_alert",
	// ...) calls into these declarative files. Scanned the same way as Go
	// source (same regex, same ligature cross-check): a JSON field name or
	// value coinciding with the icon-name shape and also happening to be a
	// real ligature is exactly as harmless here as it would be in Go source
	// -- the check only ever adds confirmed-real icons to referencedIcons,
	// never a false failure.
	err = filepath.WalkDir("../internal/dashboardengine/schemas", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() && strings.HasSuffix(p, ".json") {
			goFiles = append(goFiles, p)
		}
		return nil
	})
	if err != nil {
		t.Skipf("cannot walk dashboardengine schemas (non-source environment?): %v", err)
		return
	}

	if len(goFiles) == 0 {
		t.Skip("no Go source files found — skipping (non-source environment)")
		return
	}

	referencedIcons := make(map[string]bool)
	for _, path := range goFiles {
		content, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		for _, m := range iconRe.FindAllSubmatch(content, -1) {
			candidate := string(m[1])
			if ligatures[candidate] {
				referencedIcons[candidate] = true
			}
		}
	}

	if len(referencedIcons) == 0 {
		t.Fatal("icon scan found zero icons — likely a path or regex issue")
	}

	// Every referenced icon must be in the ligature table
	// (trivially true by construction above, but we also verify
	// the ligature table is not stale vs. the source)
	t.Logf("icons referenced in source and confirmed in font: %d", len(referencedIcons))

	// Spot-check A: icons that must be found by the scan AND present in the font.
	// These appear as double-quoted string literals in the source.
	mustFindInScan := []string{"crisis_alert", "engineering", "dangerous", "inventory_2"}
	for _, icon := range mustFindInScan {
		if !referencedIcons[icon] {
			if !ligatures[icon] {
				t.Errorf("icon %q missing from vendored font — run: make check-icons", icon)
			} else {
				t.Errorf("icon %q in font but not found by scan — check source usage", icon)
			}
		}
	}

	// Spot-check B: icons that are used inside backtick HTML strings and therefore
	// not reachable by the double-quote regex scan. Verify font presence only.
	// dark_mode / light_mode are injected as innerHTML via DarkModeIcons() in layout.go:
	//   `<span class="material-icons text-xl">dark_mode</span>`
	//   `<span class="material-icons text-xl">light_mode</span>`
	mustBeInFont := []string{"dark_mode", "light_mode"}
	for _, icon := range mustBeInFont {
		if !ligatures[icon] {
			t.Errorf("icon %q missing from vendored font — run: make check-icons", icon)
		}
	}

}
